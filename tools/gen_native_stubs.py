#!/usr/bin/env python3
"""Generate managed stand-ins for every GodotSharp native callback.

GodotSharp reaches the engine exclusively through the function-pointer struct
`NativeFuncs.UnmanagedCallbacks`. The headless simulator fills that struct with
[UnmanagedCallersOnly] C# functions so the real game assembly can run in a plain
.NET process. This script reads the decompiled NativeFuncs.cs and emits one stub
per field, in declaration order, using ABI-equivalent primitive types.

Functions listed in IMPLEMENTED are expected to be provided by hand in
NativeImpl.cs (same name, `Impl_` prefix); every other one returns default and
bumps a per-function counter so unexpected engine use is visible.
"""
import re
import sys

IMPLEMENTED = {
    "godotsharp_get_class_constructor",
    "godotsharp_method_bind_get_method",
    "godotsharp_method_bind_get_method_with_compatibility",
    "godotsharp_engine_get_singleton",
    "godotsharp_dotnet_module_is_initialized",
    "godotsharp_string_new_with_utf16_chars",
    "godotsharp_string_destroy",
    "godotsharp_string_name_new_from_string",
    "godotsharp_string_name_new_copy",
    "godotsharp_string_name_destroy",
    "godotsharp_string_name_as_string",
    "godotsharp_string_new_copy",
    "godotsharp_node_path_new_from_string",
    "godotsharp_node_path_new_copy",
    "godotsharp_node_path_destroy",
    "godotsharp_node_path_as_string",
    "godotsharp_print",
    "godotsharp_print_rich",
    "godotsharp_printerr",
    "godotsharp_printt",
    "godotsharp_prints",
    "godotsharp_printraw",
    "godotsharp_pusherror",
    "godotsharp_pushwarning",
    "godotsharp_err_print_error",
    "godotsharp_internal_script_debugger_send_error",
    "godotsharp_string_simplify_path",
    "godotsharp_string_to_camel_case",
    "godotsharp_string_to_pascal_case",
    "godotsharp_string_to_snake_case",
}

R16 = {"godot_callable", "godot_signal"} | {
    f"godot_packed_{k}_array"
    for k in ("byte", "int32", "int64", "float32", "float64", "string", "vector2", "vector3", "vector4", "color")
}
R8 = {"godot_string", "godot_string_name", "godot_node_path", "godot_array", "godot_dictionary"}
PRIM = {"int", "uint", "long", "ulong", "float", "double", "nint", "void"}
GODOT_VALUE = {
    "Color", "Vector2", "Vector2I", "Vector3", "Vector3I", "Vector4", "Vector4I", "Rect2", "Rect2I",
    "Transform2D", "Transform3D", "Quaternion", "Projection", "Plane", "Basis", "Aabb", "Rid",
}


def split_args(s: str) -> list[str]:
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch == "<":
            depth += 1
        elif ch == ">":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def map_type(t: str, is_ret: bool) -> str:
    t = t.strip()
    if t.endswith("*") or t.startswith("delegate*"):
        return "nint"
    if t == "godot_bool":
        return "byte"
    if t in ("Error", "godot_error_handler_type"):
        return "int"
    if t in PRIM:
        return t
    if t in GODOT_VALUE:
        return "Godot." + t
    if t in R8:
        return "nint"
    if t in R16:
        return "R16"
    if t == "godot_variant":
        return "R24"
    raise ValueError(f"unmapped type {t!r} (ret={is_ret})")


def main(src: str, dst: str) -> None:
    text = open(src, encoding="utf-8").read()
    start = text.index("private struct UnmanagedCallbacks")
    body = text[start: text.index("private static bool initialized")]
    fields = re.findall(r"delegate\* unmanaged<(.*)> (\w+);", body)
    lines = [
        "// <auto-generated> by tools/gen_native_stubs.py — do not edit.</auto-generated>",
        "#pragma warning disable CS8500",
        "using System.Runtime.CompilerServices;",
        "using System.Runtime.InteropServices;",
        "namespace Sts2Sim.GodotShim;",
        "",
        "public static unsafe partial class NativeStubs",
        "{",
        f"    public const int Count = {len(fields)};",
        "    public static readonly string[] Names = {",
    ]
    lines += [f'        "{name}",' for _, name in fields]
    lines += ["    };", "    public static readonly long[] Calls = new long[Count];", ""]
    table = []
    for idx, (sig, name) in enumerate(fields):
        parts = split_args(sig)
        ret = map_type(parts[-1], True)
        params = [map_type(p, False) for p in parts[:-1]]
        plist = ", ".join(f"{p} a{i}" for i, p in enumerate(params))
        fptr = "delegate* unmanaged<" + ", ".join(params + [ret]) + ">"
        target = name if name not in IMPLEMENTED else f"Impl_{name}"
        table.append(f"        p[{idx}] = (nint)({fptr})&{target};")
        if name in IMPLEMENTED:
            continue
        lines.append("    [UnmanagedCallersOnly]")
        if ret == "void":
            lines.append(f"    static void {name}({plist}) {{ Calls[{idx}]++; }}")
        else:
            lines.append(f"    static {ret} {name}({plist}) {{ Calls[{idx}]++; return default; }}")
    lines += ["", "    static void Fill(nint* p)", "    {"] + table + ["    }", "}", ""]
    open(dst, "w", encoding="utf-8").write("\n".join(lines))
    print(f"wrote {len(fields)} stubs ({len(IMPLEMENTED)} hand-implemented) -> {dst}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
